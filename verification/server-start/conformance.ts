import process from "node:process";

import * as Option from "effect/Option";

import {
  type Apply,
  applyOf,
  listenerOf,
  RunId,
  ServerName,
  stateOf,
} from "#rigging/core/server/domain.ts";

const tla = (value: unknown): string =>
  typeof value === "boolean"
    ? value
      ? "TRUE"
      : "FALSE"
    : Array.isArray(value)
      ? `<<${value.map(tla).join(", ")}>>`
      : JSON.stringify(value);

const set = (rows: readonly unknown[]) =>
  `{\n  ${rows.map(tla).join(",\n  ")}\n}`;

const flags = [false, true] as const;

const modelApply = (apply: Apply) =>
  ({ None: "none", Applying: "applying", Applied: "done", Failed: "failed" })[
    apply._tag
  ];

const codeApply = (apply: string): Apply =>
  apply === "none"
    ? { _tag: "None" }
    : apply === "applying"
      ? { _tag: "Applying" }
      : apply === "done"
        ? { _tag: "Applied" }
        : { _tag: "Failed", failure: "f", diagnostic: null };

const name = ServerName.make("dev");
const run = RunId.make("bbbbbbbb");
const record = {
  rigging: 1,
  name,
  run,
  pid: 10,
  group: 20,
  startedAt: "2026-11-18T00:00:00.000Z",
  command: ["vp", "run", "dev:serve"],
} as const;

const stateRows = flags.flatMap((rec) =>
  flags.flatMap((runner) =>
    flags.flatMap((group) =>
      flags.flatMap((answering) =>
        ["none", "applying", "done", "failed"].map((apply) => [
          rec,
          runner,
          group,
          answering,
          apply,
          stateOf(rec ? Option.some(record) : Option.none(), {
            runner,
            group,
            answering,
            apply: codeApply(apply),
          }),
        ]),
      ),
    ),
  ),
);

const RUNNER = 10;
const COMMAND = 20;
const SIDECAR = 30;
const STRANGER = 40;

const listenerRows = flags.flatMap((sidecar) =>
  flags.flatMap((stranger) =>
    flags.map((commandAlive) => {
      const parents = new Map([
        [1, 0],
        [RUNNER, 1],
        [SIDECAR, commandAlive ? COMMAND : 1],
        [STRANGER, 1],
      ]);
      if (commandAlive) parents.set(COMMAND, RUNNER);
      const listening = [
        ...(sidecar ? [SIDECAR] : []),
        ...(stranger ? [STRANGER] : []),
      ];
      const marked = new Set(listening.filter((pid) => pid === SIDECAR));
      const tag = listenerOf(listening, parents, COMMAND, marked)._tag;
      return [
        sidecar,
        stranger,
        commandAlive,
        { Free: "free", Server: "server", Taken: "taken" }[tag],
      ];
    }),
  ),
);

const stamp = (index: number) =>
  `2026-11-18 01:00:${String(index).padStart(2, "0")}.000000000  `;

const linesOf = (event: string, first: boolean) =>
  event === "applying"
    ? [
        first
          ? "[t] INFO: Dev · dev-test"
          : "[t] INFO: Reloading stack: src/a.ts",
      ]
    : event === "done"
      ? ["[t] INFO: Done: 6 succeeded (10.0s)"]
      : first
        ? [
            "[t] ERROR: alchemy dev: run failed; keeping dev alive.",
            "Error: boom",
          ]
        : [
            "[t] ERROR: [Backend] fail (local) — RewrittenMigrationHistoryError: changed 0001_init.sql (81ms)",
            "[t] INFO: Failed: 0 succeeded, 1 failed (6.3s)",
            "[t] ERROR: alchemy dev: apply failed; keeping dev alive so healthy resources keep serving.",
            "RewrittenMigrationHistoryError: changed 0001_init.sql",
          ];

const logOf = (events: readonly string[]) => {
  const lines = [
    "==== dev start 2026-11-17T00:00:00.000Z run=aaaaaaaa",
    ...linesOf("applying", true),
    ...linesOf("failed", false),
    "==== dev exit run=aaaaaaaa code=1",
    `==== dev start 2026-11-18T00:00:00.000Z run=${run}`,
    ...events.flatMap((event, index) => linesOf(event, index === 0)),
  ];
  return lines.map((line, index) => stamp(index) + line).join("\n");
};

const sequences = (length: number): (readonly string[])[] =>
  length === 0
    ? [[]]
    : sequences(length - 1).flatMap((rest) =>
        ["applying", "done", "failed"].map((event) => [...rest, event]),
      );

const applyRows = [0, 1, 2, 3, 4]
  .flatMap(sequences)
  .map((events) => [events, modelApply(applyOf(logOf(events), name, run))]);

process.stdout.write(`---- MODULE CodeTables ----
\\* Generated by verification/server-start/conformance.ts from src/core/server/domain.ts.
StateOfRows == ${set(stateRows)}
ListenerRows == ${set(listenerRows)}
ApplyRows == ${set(applyRows)}
====
`);
